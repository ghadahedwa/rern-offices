 *
 * الأرقام من بياناتٍ رسمية موقَّعة، فيصلح الـseeder لتأسيس الأرصدة الافتتاحية
 * على السيرفر لا للاختبار وحده. والحراسة ليست على البيئة بل على **حال المخزن**:
 * يرفض العمل إن كان على المخزن حركةُ وارد أو نقل، فذلك يعني أنه دخل الخدمة
 * وإعادةُ جرده بلقطةٍ ورقية تُفسد أرصدة معاملاتٍ حقيقية.
 *
 * ⚠️ والأرقام **منقولةٌ بالعين من صور** لا مستوردة من مصدر رقمي. وهي بعد
 *    تسجيلها تصير أساس كل حركةٍ تالية، فتصحيحها لاحقاً تعديلٌ على رصيدٍ
 *    بُنيت عليه معاملات — لا مجرّد إعادة تشغيل.
 *
 * ⚠️ **المخزن**: البيانات صادرة عن الإدارة العامة للتعاقدات والمخازن، فكلّها
 *    تُسجَّل على المخزن **الرئيسي** (المستوى ١). الورق لا يذكر مخزناً، وهذا هو
 *    الاستنتاج الوحيد الممكن — ولو كان بعضها لمخزنٍ آخر فالتصحيح من الشاشة.
 *
 * ⚠️ يمرّ عبر `WarehouseLedger::recordOpening` لا بإدخالٍ خام في `warehouse_stocks`:
 *    الرصيد بلا حركةٍ تقابله يجعل سجلّ الحركات كاذباً — رصيدٌ ظهر من العدم.
 *    والافتتاحي **يضبط** الرصيد ولا يجمع، فإعادة التشغيل لا تضاعفه.
 *
 * ⚠️ **الشرطة في الورق (`----`) تعني صفراً** — بإفادة المستخدمة. فتُسجَّل أصحابُها
 *    بصفرٍ كغيرهم، والاتجاه المقابل هو قاعدة العرض: **الصفر يُطبَع شرطةً في
 *    البيان**، لا رقماً. والورقة نفسها غير متّسقة (بعض الأصفار مكتوبة `٠`
 *    وبعضها `----`)، وقاعدةُ العرض هذه توحّدها.
 *
 * التشغيل:  php artisan db:seed --class=WarehouseOpeningBalancesFromStatementsSeeder
 */
class WarehouseOpeningBalancesFromStatementsSeeder extends Seeder
{
    public function run(): void
    {
        $warehouse = Warehouse::whereHas('type', fn ($q) => $q->where('level', 1))->first();

        if (! $warehouse) {
            $this->command?->error('لا يوجد مخزن رئيسي (مستوى ١) — أنشئه أولاً.');

            return;
        }

        $this->command?->info("المخزن: {$warehouse->name}");

        // ⚠️ **الفحص قبل الحذف ولا يُعكَس.** حركاتٌ غير افتتاحية تعني أن المخزن دخل
        //    الخدمة فعلاً، فلا يُعاد جرده بلقطةٍ ورقية. ولو سبق الحذفُ الفحصَ لمُحي
        //    السجل الافتتاحي ثم رُفض العمل — فيبقى رصيدٌ بلا حركةٍ تُثبته.
        $live = WarehouseMovement::where('warehouse_id', $warehouse->id)
            ->where('type', '!=', 'opening')->count();

        if ($live > 0) {
            $this->command?->error("مرفوض: على المخزن {$live} حركة وارد/نقل — إعادة الجرد تُفسد أرصدتها.");

            return;
        }

        // ⚠️ الافتتاحي **يضبط** الرصيد فلا يتضاعف بإعادة التشغيل، لكنه **يُلحِق**
        //    حركةً جديدة في السجل في كل مرة — فيبدو أن جرداً افتتاحياً تكرّر.
        //    الرصيد يخرج سليماً والسجل يكذب، وهو أسوأ من خطأ يُرى.
        $stale = WarehouseMovement::where('warehouse_id', $warehouse->id)
            ->where('type', 'opening')->count();

        if ($stale > 0) {
            WarehouseMovement::where('warehouse_id', $warehouse->id)
                ->where('type', 'opening')->delete();
            $this->command?->warn("حُذفت {$stale} حركة افتتاحية سابقة على هذا المخزن.");
        }

        $done = $missing = 0;
        $notFound = [];

        foreach ($this->balances() as $categoryName => $rows) {
            $category = ItemCategory::where('name', $categoryName)->first();

            if (! $category) {
                $this->command?->warn("قسم غير موجود: {$categoryName}");
                continue;
            }

            foreach ($rows as $key => $quantity) {
                // المفتاح «الاسم» أو «الاسم|الرقم» حين يتكرّر الاسم في القسم
                [$name, $code] = array_pad(explode('|', $key), 2, null);

                $item = Item::where('item_category_id', $category->id)
                    ->where('name', $name)
                    ->when($code !== null, fn ($q) => $q->where('code', $code))
                    ->first();

                if (! $item) {
                    $notFound[] = "{$categoryName} / {$key}";
                    $missing++;
                    continue;
                }

                WarehouseLedger::recordOpening($warehouse, $item, $quantity);
                $done++;
            }

            $this->command?->info(sprintf('%-52s %3d رصيد', $categoryName, count($rows)));
        }

        $this->command?->info("سُجِّل {$done} رصيداً افتتاحياً.");

        if ($missing > 0) {
            $this->command?->warn("لم يُطابَق {$missing} صنفاً:");
            foreach ($notFound as $n) {
                $this->command?->warn("   {$n}");
            }
        }
    }

