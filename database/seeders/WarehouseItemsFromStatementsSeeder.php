     * وحدة القسم كله — تسبق الافتراضي ويسبقها تخصيصُ الصنف.
     * ⚠️ الوحدة هنا خاصّية القسم لا الصنف: بيان «فهرس التوثيق» كله دفاتر،
     *    و«أظرف قانون ٩ و٢٧» كلها حوافظ. فتحديدها صنفاً صنفاً يُغري بالسهو.
     */
    private const CATEGORY_UNITS = [
        // ⚠️ «مخزن التصوير» ليس هنا عمداً: القسم يخدم ماكينات التصوير، لكن
        //    محتواه أحبارٌ ودرام لا ماكينات — والأحبار نفسها في «مخزن الكمبيوتر»
        //    وحدتها «قطعة». فإفراده بـ«جهاز» يجعل الصنف الواحد بوحدتين.
        'نماذج قانون ٩ و٢٧'       => 'نموذج/مستند',
        'أظرف قانون ٩ لسنة ٢٠٢٢'  => 'حافظة',
        'أظرف قانون ٢٧ لسنة ٢٠١٨' => 'حافظة',
        'فهرس التوثيق'            => 'دفتر',
        'الدفتر العقاري (١)'      => 'دفتر',
    ];

    public function run(): void
    {
        $units = $this->ensureUnits();

        foreach ($this->statements() as $categoryName => $rows) {
            $category = ItemCategory::where('name', $categoryName)->first();

            if (! $category) {
                $this->command?->warn("قسم غير موجود، تُخطّي أصنافه: {$categoryName}");
                continue;
            }

            $categoryUnit = self::CATEGORY_UNITS[$categoryName] ?? self::DEFAULT_UNIT;

            foreach (array_values($rows) as $i => $row) {
                [$name, $code, $unit] = $this->parse($row, $categoryUnit);

                // ⚠️ المفتاح (القسم + الاسم + الرقم) ولا يجوز اختصاره:
                //  · بالاسم وحده تنهار ستةُ «ملف خاص شئون عاملين» في صفٍّ واحد،
                //    فالورقة تكتب لها الاسم نفسه ولا يفرّقها إلا الرقم (١١٢ ق … ١١٧ ق).
                //  · وبالرقم وحده ينهار صفّا «٤ توثيق» في فهرس التوثيق، فالرقم
                //    نفسه محمولٌ على صنفين باسمين مختلفين.
                Item::updateOrCreate(
                    ['item_category_id' => $category->id, 'name' => $name, 'code' => $code],
                    [
                        'item_unit_id' => $units[$unit] ?? $units[self::DEFAULT_UNIT],
                        'order'        => $i + 1,
                        'is_active'    => true,
                    ]
                );
            }

            $this->command?->info(sprintf('%-52s %3d صنف', $categoryName, count($rows)));
        }

        $this->command?->info('الإجمالي: '.Item::count().' صنف في '.ItemCategory::count().' قسم');
    }

    /** الصف إمّا اسم مجرّد، أو [الاسم، الرقم]، أو [الاسم، الرقم، الوحدة]. */
    private function parse(string|array $row, string $categoryUnit): array
    {
        if (is_string($row)) {
            return [$row, null, $categoryUnit];
        }

        return [
            $row[0],
            ($row[1] ?? null) ?: null,
            $row[2] ?? $categoryUnit,
        ];
    }

