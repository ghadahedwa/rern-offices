 *
 * ⚠️ البيانات منقولة بالعين من صور ممسوحة، لا مستوردة من مصدر رقمي — فالمواضع
 *    المشكوك في قراءتها محصورة في documentation/warehouse-items-review.md.
 *    لذلك هذا **seeder لا migration**: يُعاد تشغيله بعد كل تصحيح.
 *
 * ⚠️ idempotent بمفتاح (القسم + الاسم + الرقم): إعادة التشغيل تحدّث الوحدة
 *    والترتيب ولا تُكرّر الصفوف. لكن **تغيير اسمِ أو رقمِ صنفٍ في هذا الملف
 *    يُنشئ صفاً جديداً** ولا يعيد تسمية القديم — فبعد تصحيحٍ كهذا، احذف القديم.
 *
 * ⚠️ الأرصدة المكتوبة في البيانات **لم تُستورد**: الرصيد يخصّ (مخزن × صنف)
 *    ويُسجَّل من شاشة الأرصدة الافتتاحية، ولا يُعرف من الورق أيُّ مخزن يحمله.
 *
 * التشغيل:  php artisan db:seed --class=WarehouseItemsFromStatementsSeeder
 */
class WarehouseItemsFromStatementsSeeder extends Seeder
