<?php

namespace App\Reports;

use Generator;

/**
 * اختيار تخطيط «بيان بأرصدة {القسم}»: عمود واحد أم عمودان، وكم صفاً في العمود.
 *
 * ⚠️ **لا يُقدَّر التخطيط ولا يُحسب من ثابت — يُجرَّب**. جُرّب التقديران معاً
 *    فسقطا:
 *  · **بعدد الصفوف**: سقفٌ واحد لكل الأقسام يُقاس على أطولها أسماءً، فيُخرج
 *    «مخزن المستديم» (٥٢ صنفاً قصيرة الأسماء) في ورقتين، والدفتر الورقي نفسه
 *    يطبعه في **ورقة واحدة** بعمودين — وهذا هو الفرق الذي لاحظته المستخدمة.
 *  · **بعدد الأحرف**: غير مطّرد أصلاً. مقيسٌ أن «الطلبات الموقوفة والمتعارضة»
 *    (٢٧ حرفاً) يدخل سطراً، و«نموذج ٢ تصرف فى محرر مشهر ٢٧» (٢٨) ينكسر سطرين،
 *    ثم «شهادة من التصديق على التوقيعات» (٣٠) يدخل سطراً! الحروف العربية
 *    تختلف عرضاً، ووصلُها يقصّرها. و`GetStringWidth` كذّبها كذلك (٤٩مم سطر ·
 *    ٥١مم سطران · ٥٦مم سطر) لأنه يقيس الحروف منفصلة قبل الوصل.
 *
 * فالتخطيط يُختار بالتجريب: يُبنى الملف ويُعدّ صفحاته، ويُقبل **أول تخطيط
 * يدخل في عدد أوراقه المقصود**. وهي قاعدة الدفتر نفسها: عمودٌ واحد ما دام
 * يدخل ورقة، فإن فاض فعمودان، فإن فاضا فورقة ثانية.
 */
class StatementLayout
{
    /** سقف المحاولات — صمّام لا حدّ متوقَّع؛ أكبر قسم في البيانات ينجح من الأولى. */
    public const MAX_ATTEMPTS = 12;

    /**
     * الحدّ **الفيزيائي** لصفوف العمود على ورقة A4: مقيسٌ بأقصر اسمٍ ممكن
     * («زر») — ثلاثون تدخل وأربعٌ وثلاثون تفيض.
     *
     * ⚠️ ليس تقديراً لما يسع قسماً بعينه (ذلك يُجرَّب)، بل حدٌّ لا يُتجاوز مهما
     *    قصرت الأسماء. فائدته أنه يُسقط المحاولات المستحيلة سلفاً: قسمٌ بمئةٍ
     *    وستةٍ وأربعين صنفاً لا يدخل ورقتين مهما فُعل، فلا معنى لبنائهما.
     *    اختصر زمن أكبر تقرير من ثلاث ثوانٍ إلى أقل من واحدة.
     */
    public const ROWS_ABS_MAX_PER_COLUMN = 30;

    /**
     * التخطيطات المرشَّحة بالترتيب: الأضيق ورقاً أولاً، بلا المستحيل منها.
     *
     * @return Generator<array{twoUp: bool, perColumn: int, pages: int}>
     */
    public static function candidates(int $count): Generator
    {
        $count = max($count, 1);

        // العمود الواحد في خطٍّ أكبر، فما يسعه أقلّ من الحدّ الفيزيائي قطعاً
        if ($count <= self::ROWS_ABS_MAX_PER_COLUMN) {
            yield ['twoUp' => false, 'perColumn' => $count, 'pages' => 1];
        }

        $first = max(1, (int) ceil($count / (2 * self::ROWS_ABS_MAX_PER_COLUMN)));

        for ($pages = $first; $pages < $first + self::MAX_ATTEMPTS; $pages++) {
            yield [
                'twoUp'     => true,
                'perColumn' => (int) ceil($count / (2 * $pages)),
                'pages'     => $pages,
            ];
        }
    }

    /**
     * أول تخطيط يدخل في أوراقه. `$renderPages` يبني الملف ويرجع عدد صفحاته.
     *
     * @param  callable(array):int  $renderPages
     * @return array{twoUp: bool, perColumn: int, pages: int}
     */
    public static function fit(int $count, callable $renderPages): array
    {
        $layout = null;

        foreach (self::candidates($count) as $layout) {
            if ($renderPages($layout) <= $layout['pages']) {
                return $layout;
            }
        }

        // استُنفدت المحاولات: يُعتمد الأوسع ورقاً — بيانٌ بأوراق زائدة أهون من لا بيان
        return $layout;
    }
}
